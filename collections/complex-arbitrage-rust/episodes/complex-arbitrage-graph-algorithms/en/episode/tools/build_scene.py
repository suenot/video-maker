#!/usr/bin/env python3
"""Build one scene into a standalone HyperFrames project.

usage: python3 tools/build_scene.py <scene_id | all> [--debug]

Concatenates, inside one IIFE of tools/shell.html:
  style/kit/*.js (sorted)                       the collection's drawing kit
  generated header: K, P, SCENE, SYNC           scene timing + narration slice
  episode/lib/*.js (sorted)                      narration, hosts, transitions, runtime
  episode/scenes/<id>/src/*.js (sorted)          the scene itself (ends with RUN(draw))
and writes scenes/<id>/index.html (+ assets/, hyperframes.json, meta.json).
--debug writes scenes/<id>/preview/ instead, with a time/speaker/word strip
at the bottom of every frame (for snapshots; never render it).
"""
import glob, json, math, os, shutil, sys

EP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COLL = os.path.abspath(os.path.join(EP, "..", "..", "..", ".."))
KIT = os.path.join(COLL, "style", "kit")


def load_manifest():
    m = json.load(open(os.path.join(EP, "scenes.json"), encoding="utf-8"))
    sc = m["scenes"]
    for i, s in enumerate(sc):
        s["in"] = sc[i - 1]["out"] if i > 0 else "cut"
        if i > 0 and abs(sc[i - 1]["end"] - s["start"]) > 1e-6:
            sys.exit(f"scenes.json: {sc[i-1]['id']} ends at {sc[i-1]['end']} but {s['id']} starts at {s['start']}")
    return m


def sync_slice(start, end):
    d = json.load(open(os.path.join(EP, "data", "sync.json"), encoding="utf-8"))
    fps = d["fps"]
    f0 = max(0, int(math.floor((start - 2) * fps)))
    f1 = int(math.ceil((end + 2) * fps))
    words = [w for w in d["words"] if w[1] >= start - 2 and w[0] <= end + 2]
    return {"fps": fps, "f0": f0, "env": d["env"][f0:f1], "spk": d["spk"][f0:f1], "words": words}


def build(scene, debug=False):
    sid = scene["id"]
    sdir = os.path.join(EP, "scenes", sid)
    if not os.path.isdir(os.path.join(sdir, "src")):
        print("skip (no src):", sid); return None
    out_dir = os.path.join(sdir, "preview") if debug else sdir
    os.makedirs(out_dir, exist_ok=True)
    meta = {k: scene.get(k) for k in ("id", "slide", "start", "end", "title", "in", "out", "inAt", "outAt")}
    meta["debug"] = bool(debug)
    header = "/* ---- generated by tools/build_scene.py ---- */\nconst K = CK, P = CK.P;\n"
    header += "const SCENE = " + json.dumps(meta, ensure_ascii=False) + ";\n"
    header += "const SYNC = " + json.dumps(sync_slice(scene["start"], scene["end"]), ensure_ascii=False, separators=(",", ":")) + ";\n"
    parts = [open(f, encoding="utf-8").read() for f in sorted(glob.glob(os.path.join(KIT, "*.js")))]
    parts.append(header)
    parts += [open(f, encoding="utf-8").read() for f in sorted(glob.glob(os.path.join(EP, "lib", "*.js")))]
    parts += [open(f, encoding="utf-8").read() for f in sorted(glob.glob(os.path.join(sdir, "src", "*.js")))]
    js = "\n".join(parts)
    fonts = open(os.path.join(KIT, "fonts", "fonts.css"), encoding="utf-8").read().replace("FONTDIR/", "assets/fonts/")
    shell = open(os.path.join(EP, "tools", "shell.html"), encoding="utf-8").read()
    dur = round(scene["end"] - scene["start"], 3)
    html = shell.replace("/*__FONTS__*/", fonts).replace("/*__SCRIPT__*/", js).replace("__DUR__", str(dur)).replace("__ID__", sid)
    open(os.path.join(out_dir, "index.html"), "w", encoding="utf-8").write(html)
    fd = os.path.join(out_dir, "assets", "fonts"); os.makedirs(fd, exist_ok=True)
    for f in glob.glob(os.path.join(KIT, "fonts", "*.woff2")):
        dst = os.path.join(fd, os.path.basename(f))
        if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(f): shutil.copy2(f, dst)
    shutil.copy2(os.path.join(KIT, "vendor", "gsap.min.js"), os.path.join(out_dir, "assets", "gsap.min.js"))
    json.dump({"$schema": "https://hyperframes.heygen.com/schema/hyperframes.json", "paths": {"blocks": "compositions", "components": "compositions/components", "assets": "assets"}},
              open(os.path.join(out_dir, "hyperframes.json"), "w"), indent=2)
    json.dump({"id": sid, "name": sid}, open(os.path.join(out_dir, "meta.json"), "w"), indent=2)
    print(f"{sid}: {'preview/' if debug else ''}index.html {len(html)//1024} KB, {dur} s")
    return out_dir


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    debug = "--debug" in sys.argv
    m = load_manifest()
    target = args[0] if args else "all"
    for s in m["scenes"]:
        if target == "all" or s["id"] == target or s["id"].startswith(target + "_"):
            build(s, debug)


if __name__ == "__main__":
    main()
