#!/usr/bin/env python3
"""Create the episode dir for one prepped episode: scenes.json, data/sync.json, .gitignore, REVIEW.md.

usage: init_episode.py <collection>/episodes/<slug>/<lang> [--max 60] [--host-a more|low|high] [--force]

- Reads prep/timeline.json (slide start/end) and prep/SCENES.md ("## Slide N: Title. a to b").
- Runs build_sync.py (narration sync data) unless data/sync.json exists.
- One scene per slide; a slide longer than --max seconds (default 60) is split into
  sub-scenes a, b, c ... at sentence starts nearest to equal parts.
- Scene ids: s<NN><letter?>_<slug of the slide title>, e.g. s04_bellman_ford_rust, s01b_...
- Transitions: "wave" between slides, "cut" inside a slide, "end" on the last scene.
  The last scene runs to the end of the audio.
Edit scenes.json by hand afterwards if a split point or a transition should differ
(keep it contiguous; build_scene.py checks).
"""
import json, math, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from epcommon import Episode, ENGINE

GITIGNORE = """# generated by collections/_episode/tools (build_scene / snap / render)
scenes/*/index.html
scenes/*/assets/
scenes/*/preview/
scenes/*/hyperframes.json
scenes/*/meta.json
scenes/*/snapshots/*.png
scenes/*/snapshots/snap.log
scenes/*/snapshots/contact-sheet*.jpg
renders/
"""


def slugify(s, n=4):
    w = re.findall(r"[a-z0-9]+", s.lower().replace("'", ""))
    stop = {"the", "a", "an", "of", "and", "to", "for", "in", "on", "with", "vs", "from"}
    w = [x for x in w if x not in stop] or w
    return "_".join(w[:n]) or "scene"


def main():
    args = sys.argv[1:]
    if not args: sys.exit(__doc__)
    lang_dir = os.path.abspath(args[0]); opts = args[1:]
    mx = float(opts[opts.index("--max") + 1]) if "--max" in opts else 60.0
    host = opts[opts.index("--host-a") + 1] if "--host-a" in opts else "more"
    epdir = os.path.join(lang_dir, "episode")
    os.makedirs(os.path.join(epdir, "data"), exist_ok=True)
    os.makedirs(os.path.join(epdir, "scenes"), exist_ok=True)
    if os.path.exists(os.path.join(epdir, "scenes.json")) and "--force" not in opts:
        sys.exit("scenes.json exists (use --force to overwrite)")
    open(os.path.join(epdir, "scenes.json"), "w").write('{"scenes": []}')  # marker so Episode() resolves
    ep = Episode(epdir)
    if not os.path.exists(ep.audio): sys.exit("missing audio: " + ep.audio)
    sync = os.path.join(epdir, "data", "sync.json")
    if not os.path.exists(sync):
        subprocess.run([sys.executable, os.path.join(ENGINE, "tools", "build_sync.py"), epdir, "--host-a", host], check=True)
    d = json.load(open(sync))
    starts = [p[0] for p in d["phrases"]]
    tl = json.load(open(os.path.join(ep.prep, "timeline.json")))["timeline"]
    titles = {}
    sm = os.path.join(ep.prep, "SCENES.md")
    if os.path.exists(sm):
        for m in re.finditer(r"^## Slide (\d+):\s*(.+?)\.\s+[\d.]+ to ", open(sm, encoding="utf-8").read(), re.M):
            titles[int(m.group(1))] = m.group(2)
    scenes = []
    for i, s in enumerate(tl):
        n = i + 1
        a, b = float(s["start"]), float(s["end"])
        if i == len(tl) - 1: b = round(d["dur"], 3)
        k = max(1, math.ceil((b - a) / mx - 0.15))
        cuts = [a]
        for j in range(1, k):
            t = a + (b - a) * j / k
            near = min((x for x in starts if a + 8 < x < b - 8), key=lambda x: abs(x - t), default=round(t, 1))
            cuts.append(round(near, 1))
        cuts.append(b)
        slug = slugify(titles.get(n, f"slide {n}"))
        for j in range(k):
            sid = f"s{n:02d}{chr(97 + j) if k > 1 else ''}_{slug}"
            scenes.append({"id": sid, "slide": n, "start": round(cuts[j], 3), "end": round(cuts[j + 1], 3),
                           "out": "cut" if j < k - 1 else "wave", "title": titles.get(n, f"Slide {n}") + (f" (part {j + 1}/{k})" if k > 1 else "")})
    scenes[-1]["out"] = "end"
    man = {"fps": 30, "audio_dur": d["dur"], "collection": ep.collection, "slug": ep.slug, "lang": ep.lang,
           "note": "Contiguous scene list in episode-global seconds (audio time). out = transition into the next scene: wave | iris | cut (end on the last). Generated by _episode/tools/init_episode.py; edit by hand if needed.",
           "scenes": scenes}
    with open(os.path.join(epdir, "scenes.json"), "w", encoding="utf-8") as f:
        f.write(json.dumps(man, ensure_ascii=False, indent=1))
    if not os.path.exists(os.path.join(epdir, ".gitignore")): open(os.path.join(epdir, ".gitignore"), "w").write(GITIGNORE)
    if not os.path.exists(os.path.join(epdir, "REVIEW.md")): open(os.path.join(epdir, "REVIEW.md"), "w").write(f"# Review log: {ep.slug} ({ep.lang})\n\nOne section per scene id, round by round: concrete defects found in viewed frames and how they were fixed.\n")
    print(f"{ep.collection}/{ep.slug}/{ep.lang}: {len(scenes)} scenes, {d['dur']:.1f} s -> {epdir}/scenes.json")
    for s in scenes: print(f"  {s['id']:40s} {s['start']:8.1f} {s['end']:8.1f}  {s['end']-s['start']:5.1f} s  {s['out']}")


if __name__ == "__main__":
    main()
