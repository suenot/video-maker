#!/usr/bin/env python3
"""Build one scene (or all) of an episode into standalone HyperFrames projects.

usage: build_scene.py [episode_dir] <scene_id | prefix | all> [--debug]

Concatenates, inside one IIFE of tools/shell.html:
  <collection>/style/kit/*.js            the collection's drawing kit (sorted)
  generated header                       K, P, SCENE, SYNC (scene timing + narration slice)
  engine lib + collection episode lib    _episode/lib/*.js and <collection>/style/episode/*.js,
                                         merged by file name (a collection file replaces the
                                         engine file with the same name), sorted
  scenes/<id>/src/*.js                   the scene itself (ends with RUN(draw))
-> scenes/<id>/index.html (+ assets/, hyperframes.json, meta.json).
--debug writes scenes/<id>/preview/ instead, with a time / speaker / word strip on every frame.
"""
import glob, json, math, os, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from epcommon import ENGINE, episode_from_args


def sync_slice(ep, start, end):
    d = json.load(open(os.path.join(ep.dir, "data", "sync.json"), encoding="utf-8"))
    fps = d["fps"]
    f0 = max(0, int(math.floor((start - 2) * fps)))
    f1 = int(math.ceil((end + 2) * fps))
    words = [w for w in d["words"] if w[1] >= start - 2 and w[0] <= end + 2]
    return {"fps": fps, "f0": f0, "env": d["env"][f0:f1], "spk": d["spk"][f0:f1], "words": words}


def lib_files(ep):
    files = {os.path.basename(f): f for f in glob.glob(os.path.join(ENGINE, "lib", "*.js"))}
    files.update({os.path.basename(f): f for f in glob.glob(os.path.join(ep.coll_lib, "*.js"))})
    return [files[k] for k in sorted(files)]


def build(ep, scene, debug=False):
    sid = scene["id"]
    sdir = os.path.join(ep.dir, "scenes", sid)
    if not os.path.isdir(os.path.join(sdir, "src")):
        print("skip (no src):", sid); return None
    out_dir = os.path.join(sdir, "preview") if debug else sdir
    os.makedirs(out_dir, exist_ok=True)
    meta = {k: scene.get(k) for k in ("id", "slide", "start", "end", "title", "in", "out", "inAt", "outAt")}
    meta["debug"] = bool(debug)
    ns = ep.namespace()
    header = f"/* ---- generated by _episode/tools/build_scene.py ---- */\nconst K = window.{ns}, P = K.P;\n"
    header += "const SCENE = " + json.dumps(meta, ensure_ascii=False) + ";\n"
    header += "const SYNC = " + json.dumps(sync_slice(ep, scene["start"], scene["end"]), ensure_ascii=False, separators=(",", ":")) + ";\n"
    parts = [open(f, encoding="utf-8").read() for f in sorted(glob.glob(os.path.join(ep.kit, "*.js")))]
    parts.append(header)
    parts += [open(f, encoding="utf-8").read() for f in lib_files(ep)]
    parts += [open(f, encoding="utf-8").read() for f in sorted(glob.glob(os.path.join(sdir, "src", "*.js")))]
    js = "\n".join(parts)
    fonts_css = os.path.join(ep.kit, "fonts", "fonts.css")
    fonts = open(fonts_css, encoding="utf-8").read().replace("FONTDIR/", "assets/fonts/") if os.path.exists(fonts_css) else ""
    shell = open(os.path.join(ENGINE, "tools", "shell.html"), encoding="utf-8").read()
    dur = round(scene["end"] - scene["start"], 3)
    html = shell.replace("/*__FONTS__*/", fonts).replace("/*__SCRIPT__*/", js).replace("__DUR__", str(dur)).replace("__ID__", sid)
    open(os.path.join(out_dir, "index.html"), "w", encoding="utf-8").write(html)
    fd = os.path.join(out_dir, "assets", "fonts"); os.makedirs(fd, exist_ok=True)
    for f in glob.glob(os.path.join(ep.kit, "fonts", "*.woff2")):
        dst = os.path.join(fd, os.path.basename(f))
        if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(f): shutil.copy2(f, dst)
    gsap = glob.glob(os.path.join(ep.kit, "vendor", "gsap*.js"))
    shutil.copy2(gsap[0], os.path.join(out_dir, "assets", "gsap.min.js"))
    json.dump({"$schema": "https://hyperframes.heygen.com/schema/hyperframes.json", "paths": {"blocks": "compositions", "components": "compositions/components", "assets": "assets"}},
              open(os.path.join(out_dir, "hyperframes.json"), "w"), indent=2)
    json.dump({"id": sid, "name": sid}, open(os.path.join(out_dir, "meta.json"), "w"), indent=2)
    print(f"{sid}: {'preview/' if debug else ''}index.html {len(html)//1024} KB, {dur} s ({ep.collection}, kit {ns})")
    return out_dir


def main():
    ep, args = episode_from_args(sys.argv[1:])
    debug = "--debug" in args
    args = [a for a in args if not a.startswith("--")]
    target = args[0] if args else "all"
    for s in ep.manifest()["scenes"]:
        if target == "all" or s["id"] == target or s["id"].startswith(target + "_"):
            build(ep, s, debug)


if __name__ == "__main__":
    main()
